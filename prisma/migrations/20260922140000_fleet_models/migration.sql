-- HOURLY fare cards, for every city.
-- ---------------------------------------------------------------------------
-- A rental still needs a fare_config row: quote.service looks one up by
-- (city, class, HOURLY) BEFORE it reads the package, and throws
-- FARE_CONFIG_MISSING without it. That is what stopped airport trips working.
--
-- hourly_rate is the sheet's extra-hour rate and per_km its extra-km rate, so
-- the flexible "any hours" option and the overage on a fixed package price
-- consistently. minimum_fare is one extra hour — a floor, never the trip price.
INSERT INTO "fare_configs"
  ("city_id","vehicle_class","trip_type","base_fare","per_km","minimum_fare",
   "hourly_rate","hourly_km_per_hour","effective_from")
SELECT c."id", v.vehicle_class, 'HOURLY', 0, v.extra_km, v.extra_hour,
       v.extra_hour, 10, TIMESTAMP '2020-01-01 00:00:00'
FROM "cities" c
CROSS JOIN (VALUES
  ('swift-dzire',      150.00, 14.00),
  ('ertiga',           200.00, 18.00),
  ('innova',           200.00, 18.00),
  ('innova-crysta',    250.00, 20.00),
  ('innova-hycross',   300.00, 25.00),
  ('tempo-12',         250.00, 27.00),
  ('urbania-maharaja', 400.00, 40.00),
  ('urbania-13',       300.00, 35.00),
  ('urbania-16',       350.00, 40.00),
  ('tempo-17',         300.00, 33.00),
  ('benz-22',          400.00, 50.00),
  ('benz-28',          500.00, 55.00),
  ('benz-33',          500.00, 58.00)
) AS v(vehicle_class, extra_hour, extra_km)
WHERE NOT EXISTS (
  SELECT 1 FROM "fare_configs" fc
  WHERE fc."city_id" = c."id"
    AND fc."vehicle_class" = v.vehicle_class
    AND fc."trip_type" = 'HOURLY'
);