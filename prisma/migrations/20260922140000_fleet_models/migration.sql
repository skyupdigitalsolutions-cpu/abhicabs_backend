-- Rental packages, for EVERY city.
-- ---------------------------------------------------------------------------
-- The rate sheet came from Hyderabad but the client offers these models across
-- every state on the service list, so the rows are generated by CROSS JOIN
-- against `cities` rather than hardcoding a city id. One INSERT covers however
-- many cities exist today.
--
-- NOTE: a city added LATER gets no packages from this migration. Adding a city
-- must be followed by seeding its packages, or its riders see an empty rental
-- list. Worth doing in the admin flow that creates a city.
--
-- Every package includes 80 km regardless of duration — that is what the sheet
-- says. The 12-hour coaches give twice the time and the same distance.
INSERT INTO "rental_packages"
  ("city_id","vehicle_class","label","included_hours","included_km",
   "package_fare","extra_per_hour","extra_per_km","sort_order")
SELECT c."id", v.vehicle_class, v.label, v.hours, v.km,
       v.fare, v.extra_hour, v.extra_km, v.sort_order
FROM "cities" c
CROSS JOIN (VALUES
